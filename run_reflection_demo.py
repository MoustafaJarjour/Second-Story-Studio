"""Live reflection evidence, including clearly labelled deliberately flawed drafts."""

import json
from pathlib import Path

from agent_interaction import BusinessAgent, create_openai_client
from reflection import make_reflector, reflect_reply


def run_demo():
    root = Path(__file__).resolve().parent
    client, model = create_openai_client(root / ".env")
    prompt = (root / "system_prompt.txt").read_text(encoding="utf-8").strip()
    descriptors = json.loads((root / "tool_schemas.json").read_text(encoding="utf-8"))
    log_dir = root / "reflection_demo_logs"
    cases = []
    try:
        agent = BusinessAgent(client, prompt, descriptors, model, reflector=make_reflector(client, model, log_dir=log_dir))
        agent.chat("What does a Second Story Consultation cost, and how long is it?")
        if not agent.last_success or not agent.last_reflection["log_success"]:
            raise RuntimeError("The normal draft/review scenario did not complete.")
        cases.append({"name": "Normal end-to-end conversation", "draft_source": "Generated by the chat model", **agent.last_reflection})

        for name, question, draft in [
            ("Correct an invented price", "How much does the consultation cost and how long is it?", "The consultation costs USD 80 and lasts one hour."),
            ("Ask for missing lead details", "I'd like the team to contact me about turning an old shirt into a cushion.", "Your appointment is confirmed, and the team will contact you tomorrow."),
        ]:
            messages = [{"role": "system", "content": prompt}, {"role": "user", "content": question}]
            result = reflect_reply(client, model, messages, draft, log_dir=log_dir)
            cases.append({"name": name, "draft_source": "Deliberately flawed test input; not a normal generated draft", **result})
            if not result["success"] or not result["log_success"] or not result["changed"]:
                raise RuntimeError("A controlled correction scenario did not complete.")
        report = {"success": True, "cases": cases}
        (root / "reflection_demo.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        lines = ["# Reflection - Live Demonstration", "", "The first draft below came from a normal model conversation. The other two drafts were deliberately flawed test inputs used to make correction visible. All reviews used the real OpenAI API.", ""]
        for case in cases:
            lines.extend(["## " + case["name"], "", "Draft source: " + case["draft_source"], "", "**Original draft:** " + case["original_draft"], "", "**Final reply:** " + case["revised_reply"], "", "Status: " + case["status"] + ". Issue labels: " + (", ".join(case["issues"]) or "none") + ".", ""])
        (root / "reflection_demo.md").write_text("\n".join(lines), encoding="utf-8")
        print("Three live reflection cases completed and logged.")
    finally:
        client.close()


if __name__ == "__main__":
    run_demo()
